/* Inventory dashboard — funnel, abandonment, stockouts, slow movers, forecast. */

const COLORS = { primary: "#0f766e", warn: "#b45309", danger: "#b91c1c", muted: "#9ca3af" };

function cell(text, klass) {
  const td = document.createElement("td");
  td.textContent = text;
  if (klass) td.className = klass;
  return td;
}

async function loadFunnel() {
  const r = await fetch("/api/analytics/funnel").then((r) => r.json());
  const labels = ["Views", "Add to cart", "Started checkout", "Purchased"];
  const data = [r.views, r.add_to_cart, r.started_checkout, r.purchased];
  new Chart(document.getElementById("funnelChart"), {
    type: "bar",
    data: { labels, datasets: [{ data, backgroundColor: COLORS.primary }] },
    options: {
      maintainAspectRatio: false,
      indexAxis: "y",
      scales: { x: { ticks: { callback: (v) => fmtInt(v) } } },
      plugins: { legend: { display: false } },
    },
  });
}

async function loadAbandonment() {
  const r = await fetch("/api/analytics/cart-abandonment").then((r) => r.json());
  document.getElementById("abandonment-rate").textContent = fmtPct(r.abandonment_rate);
  document.getElementById("abandonment-detail").textContent =
    `${fmtInt(r.abandoned)} abandoned / ${fmtInt(r.total)} carts in last 30 days`;
}

async function loadStockouts() {
  const rows = await fetch("/api/analytics/stockouts-at-risk").then((r) => r.json());
  const tbody = document.querySelector("#stockoutsTable tbody");
  tbody.replaceChildren();
  for (const x of rows) {
    const tr = document.createElement("tr");
    const days = cell(x.days_of_cover ?? "—", "num");
    if (x.days_of_cover != null && x.days_of_cover < 7) days.style.color = COLORS.danger;
    else if (x.days_of_cover != null && x.days_of_cover < 14) days.style.color = COLORS.warn;
    tr.append(
      cell(x.sku),
      cell([x.size, x.color].filter(Boolean).join(" / ")),
      cell(fmtInt(x.on_hand), "num"),
      cell(Number(x.units_per_day || 0).toFixed(2), "num"),
      days,
    );
    tbody.append(tr);
  }
}

async function loadSlowMovers() {
  const rows = await fetch("/api/analytics/slow-movers").then((r) => r.json());
  const tbody = document.querySelector("#slowMoversTable tbody");
  tbody.replaceChildren();
  for (const x of rows) {
    const tied = Number(x.on_hand || 0) * Number(x.cost || 0);
    const tr = document.createElement("tr");
    tr.append(
      cell(x.sku),
      cell(x.name),
      cell(x.brand),
      cell(fmtInt(x.units_sold), "num"),
      cell(fmtInt(x.on_hand), "num"),
      cell(fmtMoney(tied), "num"),
    );
    tbody.append(tr);
  }
}

async function loadForecast() {
  // The forecast is produced by the ML job and read either from a static JSON
  // or via an API. For the demo we fetch a static file under /static/forecast.json
  // (generated by ml/run_forecast.py).
  // Prefer the API endpoint (reads from GCS in prod, local file in dev);
  // fall back to the static asset if the endpoint is missing or 404s.
  let pred = [];
  for (const url of ["/api/ml/forecast", "/static/forecast.json"]) {
    try {
      const r = await fetch(url);
      if (r.ok) { pred = await r.json(); break; }
    } catch {
      /* try next */
    }
  }
  if (!pred.length) {
    document.getElementById("forecastChart").replaceWith(
      Object.assign(document.createElement("p"), {
        className: "muted small",
        textContent: "No forecast file yet. Run `python ml/run_forecast.py` to generate one.",
      })
    );
    return;
  }
  const labels = pred.map((p) => p.ds);
  const yhat = pred.map((p) => p.yhat);
  const lo = pred.map((p) => p.yhat_lower);
  const hi = pred.map((p) => p.yhat_upper);
  new Chart(document.getElementById("forecastChart"), {
    type: "line",
    data: {
      labels,
      datasets: [
        { label: "Upper", data: hi, borderColor: "transparent", backgroundColor: "rgba(15,118,110,.15)", fill: "+1", pointRadius: 0 },
        { label: "Lower", data: lo, borderColor: "transparent", pointRadius: 0 },
        { label: "Forecast", data: yhat, borderColor: COLORS.primary, tension: 0.25, pointRadius: 0 },
      ],
    },
    options: {
      maintainAspectRatio: false,
      scales: { y: { ticks: { callback: (v) => `$${(v / 1000).toFixed(0)}k` } } },
      plugins: { legend: { display: false } },
    },
  });
}

Promise.all([loadFunnel(), loadAbandonment(), loadStockouts(), loadSlowMovers(), loadForecast()]);
